"""
STANDALONE, config-CSV-driven architecture search comparing TWO hypernetwork training
strategies across many random main-net (f) architectures. Separate from train_loo.py and
every train_loo_basediff*/train_loo_deltaweights* script -- only READS (imports, unmodified)
data_loader.py, model.py's HyperNetwork/main_net_forward/main_net_n_params/ACTIVATION_FNS,
and train_loo.py's build_tensors/train_hypernet/evaluate (the "original" strategy is just
train_loo.py's own pipeline, reused as-is).

Two strategies TRAINED, same f-architecture set, same gm1_weight, plus a third DERIVED one:
  "original" -- train_loo.py's pipeline: H(Vgsq,Vdsq) -> theta -> f(Vgs,Vds;theta). Standard
                6-fold LOO (train on 5, hold out 1).
  "delta"    -- train_loo_deltaweights_reg.py's pipeline, reimplemented here WITH gm1 support
                added (the original script didn't have it): theta_base fit once on BASE_KEY's
                own data (frozen), H_comp(Vgsq,Vdsq) -> delta_theta, theta_total = theta_base +
                delta_theta, Ids_pred = main_net_forward(theta_total, ...). BASE_KEY always in
                the training set (its own delta_theta target is ~0 by construction), so LOO
                runs over the other 5 quiescent points, 5 training points per fold.
  "ensemble" -- NOT trained: whenever both "original" and "delta" are (re)trained for the same
                (f_arch_hash, h_arch_hash) pair in the same `run` batch, their predictions are
                simply averaged at every point both cover, scored the same way, and recorded
                as a third pseudo-combo (see scratch_ensemble_original_delta.py for the
                one-off manual analysis this generalizes -- there, averaging helped when the
                two strategies were reasonably competitive, hurt when one was much worse).
                Has no saved weights of its own; its metrics.json's source_original_combo_id/
                source_delta_combo_id name the two real combos it was averaged from.

Config files (generated by the `generate` subcommand):
  f_architectures.csv -- one row per candidate f architecture: arch_hash, architecture (JSON
                         per-neuron activation lists), n_layers, n_neurons_total, n_params,
                         tanh_only (bool). Uses tanh/swish/linear; --n_tanh_only rows are
                         forced all-tanh (default 150 of 1000).
  h_architectures.csv -- one row per H size to test: h_arch_hash, h_hidden, h_layers. Default:
                         the project's current best (32,1) plus 3/4, 1/2, 1/4 of the hidden
                         width at the same depth (24,1) (16,1) (8,1).

Training and result-aggregation are deliberately TWO SEPARATE steps/subcommands, not one:

  `run` -- cross-joins f_architectures.csv x h_architectures.csv x {original,delta} and trains
           each combo as a fast-proxy fold-parallel sweep (fewer epochs, no L-BFGS -- same
           "ranking proxy, not confirmed result" convention as architecture_search.py). ONLY
           writes files under --models_dir/<combo_id>/ -- it never touches results.csv at all:
             meta.json    -- everything needed to reconstruct the model (architecture, h_hidden,
                             h_layers, n_params, strategy, gm1_weight, delta_reg_weight, base_key)
             hyper_full.pt (original) or hcomp_full.pt + theta_base.pt (delta) -- the trained weights
             metrics.json -- the LOO/full-fit scores for this combo (everything a results.csv
                             row needs); its EXISTENCE is what marks the combo "done"
           Resume logic scans the FILESYSTEM, not any CSV: a combo is skipped if
           --models_dir/<combo_id>/metrics.json already exists, so pausing (Ctrl+C at any
           point) and re-running the exact same command later picks up cleanly -- no results.csv
           needs to exist or be consulted at all. Combos are processed in --batch_size chunks
           purely for ProcessPoolExecutor parallelism grain; each combo's own metrics.json is
           written as soon as ITS training finishes, not batched/buffered.
           No paths are stored inside meta.json/metrics.json -- a combo's own directory name
           (<f_arch_hash>_<h_arch_hash>_<strategy>) is self-describing, so moving/copying
           --models_dir anywhere (a different folder, a different machine) never invalidates
           anything inside it.

  `populate` -- separately, and as many times as you like, WITHOUT retraining anything: scans
           every --models_dir/<combo_id>/metrics.json it can find and (re)builds results.csv
           from scratch (one row per combo with a metrics.json). Safe to run mid-sweep (partial
           results so far), after moving --models_dir to a new machine, or repeatedly as more
           combos finish -- it is a fast, read-only aggregation pass, no PyTorch/training
           involved. model_dir in the output CSV is just each combo's directory name (relative
           to --models_dir), so the CSV stays correct regardless of where --models_dir lives.

Usage:
  # 1. generate the two config files (1000 f-architectures, 4 H sizes)
  python architecture_search_strategies.py generate --n_f_architectures 1000 --n_tanh_only 150

  # 2. smoke test: only the first 5 rows of f_architectures.csv x 4 H sizes x 2 strategies = 40 combos
  python architecture_search_strategies.py run --n_f_architectures 5 --workers 12 --gm1_weight 0.075

  # 3. (NOT run automatically) the full sweep: all 1000 f-architectures
  python architecture_search_strategies.py run --workers 15 --gm1_weight 0.075

  # 4. any time (before, during, or after the sweep finishes) -- (re)build results.csv
  python architecture_search_strategies.py populate
"""
