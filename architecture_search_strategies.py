# ============================== "delta" strategy training (with gm1) ==============================

def rel_rmse(pred, true):
    return float(np.sqrt(np.mean((pred - true) ** 2)) / (np.abs(true).max() + 1e-30))


def fit_theta_base(df, n_params, architecture, epochs, lr, lbfgs_epochs, lbfgs_max_iter, seed,
                    weight_decay=0.0):
    """Same idea as train_loo_deltaweights_reg.py's fit_theta_base -- reimplemented here
    (not imported) since this module owns its own self-contained training code."""
    torch.manual_seed(seed)
    vgs = torch.tensor(df["Vgs"].values / VGS_SCALE, dtype=torch.float32)
    vds = torch.tensor(df["Vds"].values / VDS_SCALE, dtype=torch.float32)
    ids = torch.tensor(df["Ids"].values, dtype=torch.float32)
    norm = (ids.abs().max().item() + 1e-6) ** 2

    theta = nn.Parameter(torch.randn(n_params) * 0.3)
    opt = torch.optim.AdamW([theta], lr=lr, weight_decay=weight_decay)
    for _ in range(epochs):
        opt.zero_grad()
        pred = main_net_forward(theta, vgs, vds, architecture)
        loss = torch.mean((pred - ids) ** 2) / norm
        loss.backward()
        opt.step()

    if lbfgs_epochs > 0:
        lbfgs = torch.optim.LBFGS([theta], max_iter=lbfgs_max_iter, line_search_fn="strong_wolfe")

        def closure():
            lbfgs.zero_grad()
            pred = main_net_forward(theta, vgs, vds, architecture)
            loss = torch.mean((pred - ids) ** 2) / norm
            loss.backward()
            return loss

        for _ in range(lbfgs_epochs):
            lbfgs.step(closure)

    with torch.no_grad():
        pred = main_net_forward(theta, vgs, vds, architecture).numpy()
    return theta.detach(), rel_rmse(pred, ids.numpy())


def _delta_total_loss(hcomp, theta_base, train_keys, tensors, architecture, norm,
                       gm1_weight, gm1_norm, delta_reg_weight):
    """Same structure as train_loo.py's _total_loss (gm1 term identical), applied to
    theta_total = theta_base + delta_theta instead of a hypernetwork-only theta."""
    total = 0.0
    for k in train_keys:
        t = tensors[k]
        delta = hcomp(t["qpoint"])
        theta_total = theta_base + delta
        pred = main_net_forward(theta_total, t["vgs"], t["vds"], architecture)
        loss = torch.mean((pred - t["ids"]) ** 2) / norm[k]

        if gm1_weight > 0:
            gm_vgs_req = t["gm_vgs"].clone().requires_grad_(True)
            ids_gm = main_net_forward(theta_total, gm_vgs_req / VGS_SCALE, t["gm_vds"], architecture)
            gm1_pred = torch.autograd.grad(ids_gm, gm_vgs_req, grad_outputs=torch.ones_like(ids_gm),
                                            create_graph=True)[0]
            loss_gm1 = torch.mean((gm1_pred - t["gm1_true"]) ** 2) / gm1_norm[k]
            loss = loss + gm1_weight * loss_gm1

        if delta_reg_weight > 0:
            loss = loss + delta_reg_weight * torch.mean(delta ** 2)

        total = total + loss
    return total


def train_hcomp(train_keys, tensors, theta_base, n_params, architecture, epochs, lr, device,
                 gm1_weight, delta_reg_weight, lbfgs_epochs, lbfgs_max_iter, h_hidden, h_layers, seed,
                 weight_decay=0.0):
    torch.manual_seed(seed)
    hcomp = HyperNetwork(n_params, hidden=h_hidden, n_hidden_layers=h_layers, n_in=2).to(device)
    # AdamW (weight_decay=0.0 default is a no-op, identical to plain Adam) -- see train_loo.py's
    # train_hypernet for the same reasoning: regularizes H_comp's weights directly, aimed at
    # the generalization gap, not "escaping local minima".
    opt = torch.optim.AdamW(hcomp.parameters(), lr=lr, weight_decay=weight_decay)

    norm = {k: (np.abs(tensors[k]["ids_np"]).max() + 1e-6) ** 2 for k in train_keys}
    gm1_norm = {}
    if gm1_weight > 0:
        gm1_norm = {k: (tensors[k]["gm1_true"].abs().max().item() + 1e-6) ** 2 for k in train_keys}

    for _ in range(epochs):
        opt.zero_grad()
        loss = _delta_total_loss(hcomp, theta_base, train_keys, tensors, architecture, norm,
                                  gm1_weight, gm1_norm, delta_reg_weight)
        loss.backward()
        opt.step()

    if lbfgs_epochs > 0:
        lbfgs_opt = torch.optim.LBFGS(hcomp.parameters(), max_iter=lbfgs_max_iter, line_search_fn="strong_wolfe")

        def closure():
            lbfgs_opt.zero_grad()
            loss = _delta_total_loss(hcomp, theta_base, train_keys, tensors, architecture, norm,
                                      gm1_weight, gm1_norm, delta_reg_weight)
            loss.backward()
            return loss

        for _ in range(lbfgs_epochs):
            lbfgs_opt.step(closure)

    return hcomp


def evaluate_delta(hcomp, theta_base, key, tensors, architecture):
    t = tensors[key]
    with torch.no_grad():
        delta = hcomp(t["qpoint"])
        theta_total = theta_base + delta
        pred = main_net_forward(theta_total, t["vgs"], t["vds"], architecture).cpu().numpy()
    return rel_rmse(pred, t["ids_np"]), pred


# ============================== fold-level jobs (max parallelism grain) ==============================

def _fold_gm_safe(data, held_out, net, architecture, theta_base=None):
    """gm1/gm2/gm3 (+combined) rel-RMSE on the HELD-OUT point for a just-trained fold model,
    computed while the model is still in memory (Option C -- see the gm-metrics section).
    Returns the 4-field dict or None; never raises (a gm hiccup must not fail a training fold)."""
    try:
        predict = _predict_ids_fn(net, architecture, held_out[0], held_out[1], theta_base)
        return _gm_rel_rmses_one_qpoint(data[held_out], predict, GM_VDS_STEP)
    except Exception:
        return None


def run_fold_original(f_arch_hash, h_arch_hash, architecture, n_params, h_hidden, h_layers,
                       held_out, data, epochs, lr, gm1_weight, lbfgs_epochs, seed, weight_decay,
                       gm_smoothing="savgol"):
    torch.set_num_threads(1)
    device = torch.device("cpu")
    keys = sorted(data.keys())
    train_keys = [k for k in keys if k != held_out]
    tensors = build_tensors_full(data, device, gm_smoothing=gm_smoothing)
    hyper, _ = train_hypernet(train_keys, tensors, n_params, architecture, epochs, lr, device,
                               gm1_weight=gm1_weight, lbfgs_epochs=lbfgs_epochs,
                               h_hidden=h_hidden, h_layers=h_layers, n_in=2, log_every=0, seed=seed,
                               weight_decay=weight_decay)
    err, pred = evaluate_original(hyper, held_out, tensors, architecture, device)
    gm = _fold_gm_safe(data, held_out, hyper, architecture)
    return f_arch_hash, h_arch_hash, "original", held_out, err, pred, gm


def run_fold_delta(f_arch_hash, h_arch_hash, architecture, n_params, h_hidden, h_layers,
                    held_out, data, theta_base, epochs, lr, gm1_weight, delta_reg_weight,
                    lbfgs_epochs, seed, weight_decay, gm_smoothing="savgol"):
    torch.set_num_threads(1)
    device = torch.device("cpu")
    all_keys = sorted(data.keys())
    other_keys = [k for k in all_keys if k != BASE_KEY]
    train_keys = [BASE_KEY] + [k for k in other_keys if k != held_out]
    tensors = build_tensors_full(data, device, gm_smoothing=gm_smoothing)
    hcomp = train_hcomp(train_keys, tensors, theta_base, n_params, architecture, epochs, lr, device,
                         gm1_weight=gm1_weight, delta_reg_weight=delta_reg_weight,
                         lbfgs_epochs=lbfgs_epochs, lbfgs_max_iter=200,
                         h_hidden=h_hidden, h_layers=h_layers, seed=seed, weight_decay=weight_decay)
    err, pred = evaluate_delta(hcomp, theta_base, held_out, tensors, architecture)
    gm = _fold_gm_safe(data, held_out, hcomp, architecture, theta_base)
    return f_arch_hash, h_arch_hash, "delta", held_out, err, pred, gm


