            source_delta_combo_id=combo_id_of(f_row, h_row, "delta", hp_hash),
            gm1_weight=args.gm1_weight,
            gm_smoothing=args.gm_smoothing,
            delta_reg_weight=args.delta_reg_weight,
            weight_decay=args.weight_decay,
