            lbfgs_max_iter=args.lbfgs_max_iter,
            delta_base_epochs=args.delta_base_epochs,
            delta_base_lr=args.delta_base_lr,
            delta_base_lbfgs_epochs=args.delta_base_lbfgs_epochs,
            seed=args.seed,
            n_params_f=f_row["n_params"],
            h_hidden=h_row["h_hidden"],
            h_layers=h_row["h_layers"],
            loo_mean_rel_rmse=float(np.mean(errs)) if errs else None,
